#!/usr/bin/env python3
"""
gen_rigsetup_h.py — generate MyPi_Companion_V6/rigsetup_files.h from pi/.

Usage (from the repo root):
    python3 tools/gen_rigsetup_h.py

Every file in pi/ (except README.md, hidden files and Python caches) is
embedded as one `static const uint8_t` array, plus a manifest
RIGSETUP_FILES[] of {name, data, size}.  On boot, littlefs_mgr.ino writes
any missing file to /rigsetup/<name> on FFat; fat12_builder.ino then builds
the RIGSETUP USB disk from /rigsetup/ at runtime.

FFat names: the RIGSETUP disk uses 8.3 names without long-file-name entries,
and pi/install.sh looks for 'daemon.py' and 'pyserial.whl' on the disk.
Files whose pi/ name does not survive the 8.3 conversion are therefore
renamed via FFAT_NAMES below.

The output is deterministic: CI regenerates the header and fails if the
committed rigsetup_files.h differs.
"""

import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
PI_DIR    = REPO_ROOT / "pi"
OUTPUT_H  = REPO_ROOT / "MyPi_Companion_V6" / "rigsetup_files.h"

SKIP_NAMES    = {"README.md"}
SKIP_SUFFIXES = {".pyc", ".pyo"}

# pi/ file name -> name on FFat (/rigsetup/) and on the RIGSETUP disk
FFAT_NAMES = {
    "rig_daemon.py":                     "daemon.py",
    "pyserial-3.5-py2.py3-none-any.whl": "pyserial.whl",
}


def c_ident(name: str) -> str:
    return "_rigsetup_" + re.sub(r"[^0-9A-Za-z]", "_", name)


def main() -> None:
    if not PI_DIR.is_dir():
        sys.exit(f"ERROR: {PI_DIR} not found")

    files = sorted(
        p for p in PI_DIR.iterdir()
        if p.is_file()
        and not p.name.startswith(".")
        and p.name not in SKIP_NAMES
        and p.suffix not in SKIP_SUFFIXES
    )
    if not files:
        sys.exit("ERROR: no files found in pi/")

    out = [
        "// rigsetup_files.h — AUTO-GENERATED by tools/gen_rigsetup_h.py — do not edit",
        "// Source: pi/  →  written to /rigsetup/ on FFat at boot if missing",
        "#pragma once",
        "#include <stdint.h>",
        "#include <stddef.h>",
        "",
        "// Individual file contents as byte arrays",
    ]
    manifest = []
    total = 0
    print("Embedding pi/ files:")
    for p in files:
        data  = p.read_bytes()
        name  = FFAT_NAMES.get(p.name, p.name)
        ident = c_ident(name)
        total += len(data)
        out.append(f"static const uint8_t {ident}[] = {{")
        for i in range(0, len(data), 16):
            out.append("  " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
        out.append("};")
        manifest.append((name, ident))
        shown = p.name if name == p.name else f"{p.name} -> {name}"
        print(f"  {shown:50s} {len(data):7d} B")

    out += [
        "",
        "// Manifest: filename on FFat + pointer + size",
        "struct RigsetupFile {",
        "  const char    *name;   // e.g. \"install.sh\"",
        "  const uint8_t *data;",
        "  size_t         size;",
        "};",
        "",
        "static const RigsetupFile RIGSETUP_FILES[] = {",
    ]
    width = max(len(n) for n, _ in manifest) + 3
    iwidth = max(len(i) for _, i in manifest) + 1
    for name, ident in manifest:
        out.append(f"  {{ {(chr(34) + name + chr(34) + ',').ljust(width)} "
                   f"{(ident + ',').ljust(iwidth)} sizeof({ident}) }},")
    out += [
        "};",
        "static const size_t RIGSETUP_FILE_COUNT = sizeof(RIGSETUP_FILES) / sizeof(RIGSETUP_FILES[0]);",
        "",
    ]
    OUTPUT_H.write_text("\n".join(out), encoding="utf-8")
    print(f"\nWritten: {OUTPUT_H.relative_to(REPO_ROOT)}  ({len(files)} files, {total} bytes)")


if __name__ == "__main__":
    main()
